# ---------------------------------------------------------------------------
# Singleton causal code-LM loader (used for perplexity/burstiness)
# ---------------------------------------------------------------------------
_lm_model_instance: Optional[Any] = None
_lm_tokenizer_instance: Optional[Any] = None

# IMPORTANT: the judge model must be at least as capable as whatever
# generated the code you're checking, or it can't tell the code is
# "predictable" -- a weak model finds GPT-4/Claude-quality code just as
# surprising as human code, and everything reads as "human."
# 350M-class models are too weak for this in practice. 1B+ code-specific
# models are the practical floor; bigger is better if you have the compute.
#   - "deepseek-ai/deepseek-coder-1.3b-base"  <- default: good accuracy/CPU balance
#   - "bigcode/starcoder2-3b"                  <- stronger, multi-language, wants a GPU
#   - "bigcode/starcoder2-7b" / larger          <- best accuracy, needs a real GPU
_LM_MODEL_NAME = "deepseek-ai/deepseek-coder-1.3b-base"
_MAX_CHUNK_TOKENS = 512


def _get_lm() -> Tuple[Optional[Any], Optional[Any]]:
    """Lazy-load the causal code LM used for perplexity scoring."""
    global _lm_model_instance, _lm_tokenizer_instance
    if _lm_model_instance is not None:
        return _lm_tokenizer_instance, _lm_model_instance

    try:
        from transformers import AutoModelForCausalLM, AutoTokenizer

        logger.info(f"Loading code LM for perplexity scoring: {_LM_MODEL_NAME}")
        _lm_tokenizer_instance = AutoTokenizer.from_pretrained(_LM_MODEL_NAME)
        _lm_model_instance = AutoModelForCausalLM.from_pretrained(_LM_MODEL_NAME)
        _lm_model_instance.eval()
        logger.info("Code LM loaded successfully.")
    except Exception as e:
        logger.warning(f"Code LM unavailable ({e}). Perplexity scoring disabled.")
        _lm_model_instance = None
        _lm_tokenizer_instance = None

    return _lm_tokenizer_instance, _lm_model_instance


def _token_nlls(code: str, tokenizer, model, max_len: int = _MAX_CHUNK_TOKENS) -> List[float]:
    """
    Return per-token negative log-likelihoods for `code` under `model`.

    Files longer than max_len are split into sequential, non-overlapping
    chunks (each chunk's model context resets at the chunk boundary --
    a small accuracy cost for a large simplicity/speed win; fine for
    file-level scoring).
    """
    import torch

    enc = tokenizer(code, return_tensors="pt", truncation=False)
    input_ids = enc["input_ids"][0]
    n = input_ids.size(0)
    if n < 2:
        return []

    nlls: List[float] = []
    for start in range(0, n, max_len):
        chunk = input_ids[start:start + max_len]
        if chunk.size(0) < 2:
            continue
        chunk = chunk.unsqueeze(0)
        with torch.no_grad():
            out = model(chunk)
            logits = out.logits[0][:-1, :]
            labels = chunk[0][1:]
            log_probs = torch.log_softmax(logits, dim=-1)
            token_nll = -log_probs[range(labels.size(0)), labels]
        nlls.extend(token_nll.tolist())

    return nlls


