"""
AI Engine - AI-Generated Code Detector (v2)

PRIMARY signal: perplexity + burstiness from a causal code-LLM.
  This is the same family of technique GPTZero-style detectors use for
  prose, applied to code: AI-generated tokens are, on average, more
  "predictable" (lower perplexity) and more uniformly predictable
  (lower burstiness / less variance in surprise) to a language model
  than human-written tokens, which include more idiosyncratic choices.

SECONDARY signals: pattern/style/structural heuristics.
  These are kept as *supporting* evidence only, at low weight, because
  many of them (docstrings, type hints, formatting consistency) are
  also produced by course style guides, linters, and IDE auto-formatters
  -- they are NOT reliable AI/human discriminators on their own for
  graded coursework, and treating them as co-equal to real evidence is
  what made the previous version unreliable.

IMPORTANT: No AI-code detector is highly reliable. Treat this score as
a triage signal for human review, never as an automatic verdict.
The default perplexity anchors below are rough starting points -- you
MUST recalibrate them against your own labeled samples (see
`calibrate_from_samples` at the bottom) before trusting absolute scores.
"""
